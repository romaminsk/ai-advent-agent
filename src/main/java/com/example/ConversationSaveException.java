package com.example;

/**
 * Отдельная ситуация: модель уже ответила, но записать новую пару в файл
 * истории не удалось. Это не ошибка запроса к API: повторный платный запрос
 * не выполняется, полученный ответ не теряется — он доступен через
 * {@link #getAnswer()} для показа пользователю. История в памяти и файл
 * остаются без изменений; приложение завершает сессию, чтобы не продолжать
 * беседу с неполным контекстом.
 */
public final class ConversationSaveException extends ConversationStoreException {

    private final String answer;

    public ConversationSaveException(String answer, String reason, Throwable cause) {
        super("Ответ получен, но не сохранён в контекст: новая пара сообщений "
                + "не добавлена в историю. Причина: " + reason
                + " Чат завершается, чтобы не продолжать беседу с неполным контекстом. "
                + "Безопасный следующий шаг: перезапустите приложение — беседа "
                + "продолжится с последней успешно сохранённой пары сообщений.", cause);
        this.answer = answer;
    }

    /** Ответ модели, который уже получен и должен быть показан пользователю. */
    public String getAnswer() {
        return answer;
    }
}
