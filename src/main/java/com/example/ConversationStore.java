package com.example;

/**
 * Хранилище контекста беседы: чтение сохранённого диалога и его безопасная
 * запись. Вся работа с файлами истории сосредоточена в этом компоненте:
 * LlmAgent владеет текущим состоянием беседы в памяти, Main и TerminalUi
 * не читают и не записывают JSON истории самостоятельно.
 *
 * Реализация обязана удерживать монопольный доступ к истории (файловую
 * блокировку) с момента создания до {@link #close()} — два одновременных
 * экземпляра приложения не должны перезаписывать одну беседу.
 */
public interface ConversationStore extends AutoCloseable {

    /**
     * Читает сохранённую беседу и проверяет её структуру.
     * Если истории ещё нет — возвращает новую пустую беседу.
     * При повреждённом файле или неподдерживаемой версии формата бросает
     * {@link ConversationStoreException}: файл при этом не изменяется.
     */
    ConversationState load();

    /**
     * Полностью заменяет сохранённую беседу на переданное состояние.
     * Запись должна быть безопасной: сбой не должен оставлять после себя
     * повреждённый или частично записанный файл, предыдущая версия при
     * сбое остаётся пригодной.
     */
    void save(ConversationState state);

    /** Освобождает ресурсы хранилища, в том числе блокировку файла истории. */
    @Override
    void close();
}
